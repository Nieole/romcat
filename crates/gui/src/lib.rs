//! romcat 的界面壳。**打开它看见的是[待确认队列](queue)**（ADR-0002）。
//!
//! 核心是一个**独立的库**，界面只是它的壳（ADR-0005）。这条约束在这里落成一句可核对的
//! 话：**领域判断一条都不在这里**——排序、筛选、分页在
//! [`romcat_core::catalog::browse`]，队列怎么筛、按什么分组、一次裁决说得成不成立在
//! [`romcat_core::triage`]（`Queue`、`Axis`、`Draft`），容量怎么写成人话在
//! [`romcat_core::report::human_bytes`]，界面只负责问它要哪一段、把要来的画出来。
//! （合成数据是演示与实测用的脚手架，走的也是核心库的公开 API。它在 `demo` feature
//! 之后，**默认不编进来**：交付出去的客户端里不该有一个字节的假数据。）
//! 将来若 Windows 真机的输入法验证（票 23）没过，换掉的只是这个 crate——
//! **那正是把领域判断按在核心里的理由**。
//!
//! ## 顶上那两态
//!
//! `eframe` 收的是 [`program::Program`] 而不是 [`app::App`]：**启动那条路**——定位要开
//! 哪份库、开出**现场**、进主窗口——住在它上面，程序入口只剩解析参数与开窗。它持两态
//! ——**开场中**（[`opening`] 那一屏）与**已开库**（`App` 在画那五屏）。抬上来是为了
//! **那条路够得着测试**：`main.rs` 里的东西一条测试都碰不到，而它正是维护者第一次打开
//! 这个工具时走的路。
//!
//! ## 开场
//!
//! - [`opening`]：**开场**，五屏之外的那一屏。一个参数都不给（双击图标）看见的就是它：
//!   这个**工作目录**里有哪些**中立库**，一份一行——主库名、变体数、上次扫描时刻，
//!   **盘没挂上照样看得见**（它们住在中立库里，ADR-0009）。挑一份进主窗口，开场交出
//!   **现场**之后自己退场。**结构版本对不上的旧库照列不误**，当场说清是哪个版本对哪个
//!   版本（ADR-0023：从列表里静静消失才是最难查的那种错）。
//!
//! ## 五屏
//!
//! - [`queue`]：**待确认队列**，默认那一屏。真机上一万八千多条，**打开看见的是工具已经
//!   分好的几十批**——一级按依据形状、二级按目录或命名规律，每批带条数、那句共同依据
//!   与一组随机样本，看完一键整批通过（票 `gui-redesign/09`）。多候选那些走逐条键盘流。
//! - [`roots`]：**库**。这个库由什么构成——**一组根**（几块盘加进同一个主库，
//!   扫完收进同一份中立库）加上**数据源**（DAT 仓库、中文离线源、Switch 数据库各有多少
//!   条、上次什么时候取的）。加根、扫描、取数据源都排到任务台上跑（票 `gui-redesign/02`）。
//!   **主库只读**（ADR-0004）在这一屏是底线：加根、扫描、移除根，一个字节都不写主库。
//! - [`browse`]：**浏览**。中间那张表是 [`table`]，
//!   **一个作品一行**；左边按**平台**、**合集**、**语言**、**中文**、**识别状态**收窄，
//!   底下再压一棵可嵌套的[**条件组**](filter)——**那就是子库的规则**，筛到满意按
//!   「存成子库」原样带过去（票 `gui-redesign/04`）；
//!   右边那块面板摊开**作品 → 变体 → 文件**三层，底下那块看与改选中那个变体的元数据——
//!   **所有元数据编辑收敛在这里**（ADR-0001 的修订段），主库的元数据文件不再是编辑入口。
//!   抬头那个「刮削选中…」摊开的是[刮削面板](scrape)：四个旋钮，外加**按下去之前**
//!   就看得见的那本账——会发多少网络请求、大概多久（票 `gui-redesign/10`）。
//!   右边那块面板底下是[**媒体**那几格](media)：封面与截图**内嵌画出来**，视频是一张
//!   抽出来的首帧加一个播放标，点一下交给系统默认程序（票 `gui-redesign/07`）。
//!   抽帧走**外部 ffmpeg**，**找不到就退化成占位图标**——窗口里一个字节都不解码视频。
//!   抬头另一颗是「**★ 收藏**」：勾一批按一下，那一批底下的变体全进**收藏**——落
//!   [沉淀库](romcat_core::verdict)、锚在**内容锚**上，删掉中立库重扫也不丢
//!   （[`romcat_core::collection`]，票 `gui-redesign/06`）。它走的就是**合集**那套成员
//!   关系，所以左栏底下顺带给出自建合集。
//! - [`sublibrary`]：**子库**。选择集的规则与例外、**差量预览**、从这里触发**同步**。
//!   ADR-0016 那句「同步前必须预览差量」在这一屏是构造上的事实：同步按钮只认界面上
//!   正摆着的那份计划，规则一改它当场作废。
//! - [`task`]：**任务**。长活排在这儿跑——**跑在画帧那条线程之外**，屏上看得见进度、
//!   随时按得停、跑完留一条带耗时的历史。眼下接上来的有**排差量预览**（票 01）、
//!   扫描与取数据源（票 02）、**刮削**（票 10）、**同步**（票 15）与**识别**
//!   （票 `gui-self-sufficient/06`）；折标题与**导出**各在各自的票里接。
//!   账全在 [`romcat_core::task`] 里，这一层照旧只画和转发。
//!
//! ## 五屏共用的两样
//!
//! - [`layout`]：**面板边界**。三屏上七条边界拖得动、有下限也有上限（正中那块在任何
//!   窗口尺寸下都留得住），拖到哪儿记在**工作目录**里——不记进中立库，那份整份可再生，
//!   界面偏好放进去会被某一次重扫抹掉。
//! - [`look`]：**观感基线**。置信度四档的颜色只有这一处写、那个词只有
//!   [`Tier::label`](romcat_core::catalog::identify::Tier::label) 一处写，于是同一档在
//!   哪一屏都是同一个颜色；每一处上色的地方都跟着那个词——**颜色不是唯一线索**。
//!   **词由核心库挑，不由这一层挑**：一条候选都没有那一档在浏览屏上还要再分一次
//!   **没有候选**与**还没识别**（`WorkRow::confidence_label`，票 `gui-redesign/17`），
//!   那是一条领域判断——两个词共用第四档那一个颜色。
//!   键盘焦点也在这儿定：按钮、勾选框、可选标签与文本框拿到焦点长的是同一个样子。
//!
//! ## 这一层清掉的两个风险
//!
//! ADR-0005 给 egui 记了三个风险，其中两个自动化验得了，都在这里清掉：
//!
//! - **字体**（[`font`]）。egui 内置字体**不只缺汉字**——中文标点、假名、罗马数字 `Ⅲ`、
//!   带圈数字 `①` 全缺。所以**打包字体子集，不读系统字体**：系统字体各机器覆盖不一致
//!   （实测苹方缺 `♪`、冬青黑缺 `♪` 与 `Ⓡ`），且 macOS 上它躺在哈希命名的路径下。
//!   打包等于把「哪些字显示得出来」变成一个编译期常量。
//! - **十万行表格**（[`table`]）。`egui_extras::TableBuilder` 的 `body.rows()` 只画视口里
//!   那几十行，开销与总行数无关；而它**没有排序能力**，所以排序、筛选、分页一律下推到
//!   SQLite，内存里永远只有当前视口的内容。
//!
//! 第三个风险——**输入法**——自动化验不了：界面自动化在应用层注入事件，而输入法位于
//! 操作系统与应用之间，注入的文本根本不经过它。那一项是票 23，Windows 真机人工做。
//! 这一层为它留下的是两件事：中文输入放在**详情面板**而不是表格单元格里
//! （表格虚拟化会让正在组字的那一行滚出视口时控件消失），以及退出前先关掉输入法
//! （见 [`app::App`]）。队列那一屏把第一条推到底——**连搜索框都在面板里**，
//! 于是会碰到输入法的控件全在同一块不虚拟化的面板上，风险面缩到最小。
//! 浏览与子库那两屏照办：三屏加起来，**每一个 `TextEdit` 都长在不虚拟化的面板上**
//! （`tests/browse.rs::表格里画多少行文本输入框都是那几个` 钉住这一条）。

