//! romcat 的界面壳。
//!
//! 核心是一个**独立的库**，界面只是它的壳（ADR-0005）。这条约束在这里落成一句可核对的
//! 话：**领域判断一条都不在这里**——排序、筛选、分页在
//! [`romcat_core::catalog::browse`]，容量怎么写成人话在
//! [`romcat_core::report::human_bytes`]，界面只负责问它要哪一段、把要来的画出来。
//! （[`demo`] 造的合成数据是演示与实测用的脚手架，走的也是核心库的公开 API。）
//! 将来若 Windows 真机的输入法验证（票 23）没过，换掉的只是这个 crate。
//!
//! ## 这一层清掉的两个风险
//!
//! ADR-0005 给 egui 记了三个风险，其中两个自动化验得了，都在这里清掉：
//!
//! - **字体**（[`font`]）。egui 内置字体**不只缺汉字**——中文标点、假名、罗马数字 `Ⅲ`、
//!   带圈数字 `①` 全缺。所以**打包字体子集，不读系统字体**：系统字体各机器覆盖不一致
//!   （实测苹方缺 `♪`、冬青黑缺 `♪` 与 `Ⓡ`），且 macOS 上它躺在哈希命名的路径下。
//!   打包等于把「哪些字显示得出来」变成一个编译期常量。
//! - **十万行表格**（[`table`]）。`egui_extras::TableBuilder` 的 `body.rows()` 只画视口里
//!   那几十行，开销与总行数无关；而它**没有排序能力**，所以排序、筛选、分页一律下推到
//!   SQLite，内存里永远只有当前视口的内容。
//!
//! 第三个风险——**输入法**——自动化验不了：界面自动化在应用层注入事件，而输入法位于
//! 操作系统与应用之间，注入的文本根本不经过它。那一项是票 23，Windows 真机人工做。
//! 这一层为它留下的是两件事：中文输入放在**详情面板**而不是表格单元格里
//! （表格虚拟化会让正在组字的那一行滚出视口时控件消失），以及退出前先关掉输入法
//! （见 [`app::App`]）。

