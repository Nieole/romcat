//! **目录选择器**：弹一下系统的选目录对话框，交回一个可空的路径。这一层只做这一件事。
//!
//! 拿到路径之后做什么不在这儿，在调用方各自那条**贴路径的路**上：开场换工作目录是
//! [`crate::opening::Screen::picked`]，添加主库向导选第一个根是
//! [`crate::claim::Wizard::picked_root`]。往后谁还要挑一个目录，调 [`directory`]，
//! 把交回来的那个交给自己那条现成的路——**不另长一条「选中之后」的处理**。
//!
//! ## 这一层不测
//!
//! 对话框是**系统自己的窗口**（macOS 上是系统的打开面板，Windows 上是系统的文件对话框，
//! Linux 上经由 XDG 桌面门户，问不到门户时退到 `zenity` 命令），测试驱动不了：门禁跑的界面测试
//! 全是不开窗的（[`crate::headless`]），CI 上连显示服务器都没有。测得到的那一半——**拿到路径之后
//! 发生什么**——摆在调用方那边，测试递一个路径进去就验得着（`tests/pick.rs`）。
//!
//! 所以这里刻意薄到**没有一条自己的判断可错**：交回来的就是对话框交回来的那一个，
//! 唯一的分支只管对话框从哪儿打开。
//!
//! ## 取消与弹不出来，交回来的是同一个 `None`
//!
//! `rfd` 的同步接口不分这两样。弹不出来（远程会话；Linux 上门户与 `zenity` 都没有）时按下去
//! 什么都不发生——**所以两处的输入框都留着**，按钮的悬停提示把那条退路写明（挂单 `Q695`）。
//!
//! ## 同步地弹
//!
//! 在画帧那条线程上直接等对话框关上：对话框开着的时候这一帧停住，背后那扇窗不重画、也不响应
//! 点击（**predicted**：没开窗点过）。**任务台上跑着的活在自己的线程上照跑**，只是进度条要等
//! 对话框关上才重画。异步那条路背后那扇窗照常重画、（不递父窗口时）也照常收点击，于是要在屏上
//! 多攒一份「对话框还开着」的状态，还得回答「对话框开着时人在背后按了『算了』、或者换了工作目录，
//! 交回来的路径落到哪儿」（挂单 `Q691`）。

use std::path::{Path, PathBuf};

/// 那颗「选择…」上的悬停提示：**对话框弹不出来时的退路**——把路径贴进旁边的框。
///
/// 弹不出来与取消交回来的是同一个 `None`（见模块文档），按下去什么都不发生时人得知道
/// 还有旁边那个框可贴。几处按钮说同一句话，摆成一个常量。
pub const FALLBACK_HINT: &str = "弹不出选择窗口时（例如远程会话），也可以把路径直接贴进旁边的框";

/// 弹一个选目录的对话框，标题是 `title`，从 `start` 那个目录打开。选中了交回那个目录，
/// 取消了（或者对话框压根弹不出来）交回 `None`。
///
/// **`start` 不是一个目录时从系统默认的位置打开**：把一个不存在的起点交给对话框，
/// 有的平台（Linux 的桌面门户）会整个弹不出来——为了一个起点丢掉整个对话框不值得。
///
/// **同步**：对话框关上之前不返回，见模块文档。
#[must_use]
pub fn directory(title: &str, start: &Path) -> Option<PathBuf> {
    let mut dialog = rfd::FileDialog::new().set_title(title);
    if start.is_dir() {
        dialog = dialog.set_directory(start);
    }
    dialog.pick_folder()
}
