/// 把 [`SFC_3X3_EYES_TAIL`] 摆回一份 64 KiB 的卡带里：真实的那 256 字节落在 `0xFF00`，
/// 其余补零。
///
/// 不整份嵌进来，是因为 bsnes 的打分要读 `0xFFA0`（复位向量指向的那条指令）与 `0xFFB0`
/// （内部头），两处相隔不到 256 字节却都在 64 KiB 的末尾——为这两处嵌 64 KiB 的字面量，
/// 读代码的人一个字节也看不出所以然。
#[must_use]
pub fn snes_rom() -> Vec<u8> {
    let mut rom = vec![0u8; 0x1_0000];
    rom[0xFF00..0x1_0000].copy_from_slice(&SFC_3X3_EYES_TAIL);
    rom
}

/// 把一份卡带头补成 `len` 字节的一整份 ROM：头原样在前，后面补零。
///
/// 识别那一层要的是「一个文件」，而这里只有头。补零不影响任何一条判据——每一个偏移
/// 都在头里面，而**总长**（拷贝机头与 `.smd` 交错的唯一判据）由调用方自己定。
#[must_use]
pub fn padded(head: &[u8], len: usize) -> Vec<u8> {
    let mut rom = head.to_vec();
    rom.resize(len.max(head.len()), 0);
    rom
}

